#!/usr/bin/env bash
# One-click deployment script for AIHOT vehicle industry portal
# Usage: ./scripts/deploy.sh [server_ip] [ssh_port]
# Example: ./scripts/deploy.sh 172.17.13.184 18177

set -euo pipefail

SERVER_IP="${1:-172.17.13.184}"
SSH_PORT="${2:-18177}"
REMOTE_USER="root"
REMOTE_DIR="/opt/aihot"
SSH_OPTS="-p $SSH_PORT -o StrictHostKeyChecking=accept-new"

echo "=== AIHOT Deployment Script ==="
echo "Server: $REMOTE_USER@$SERVER_IP:$SSH_PORT"
echo "Remote directory: $REMOTE_DIR"
echo ""

# Test SSH connection
echo "[1/6] Testing SSH connection..."
if ! ssh $SSH_OPTS "$REMOTE_USER@$SERVER_IP" "echo 'SSH OK'" >/dev/null 2>&1; then
    echo "ERROR: SSH connection failed. Please run: ssh-copy-id -p $SSH_PORT $REMOTE_USER@$SERVER_IP"
    exit 1
fi
echo "✓ SSH connection successful"
echo ""

# Install Docker if not present
echo "[2/6] Checking Docker installation..."
ssh $SSH_OPTS "$REMOTE_USER@$SERVER_IP" bash <<'REMOTE_SCRIPT'
if ! command -v docker &> /dev/null; then
    echo "Installing Docker..."
    # Detect OS and install Docker
    if [ -f /etc/os-release ]; then
        . /etc/os-release
        case "$ID" in
            ubuntu|debian)
                apt-get update -qq
                apt-get install -y -qq docker.io docker-compose-v2
                systemctl enable --now docker
                ;;
            centos|rhel|fedora)
                dnf install -y -q docker docker-compose-plugin
                systemctl enable --now docker
                ;;
            alpine)
                apk add --no-cache docker docker-compose
                rc-update add docker boot
                rc-service docker start
                ;;
            *)
                echo "Unsupported OS: $ID. Please install Docker manually."
                exit 1
                ;;
        esac
    else
        echo "Cannot detect OS. Please install Docker manually."
        exit 1
    fi
    echo "✓ Docker installed"
else
    echo "✓ Docker already installed"
    # Ensure Docker Compose is available
    if ! docker compose version &> /dev/null; then
        echo "Installing Docker Compose plugin..."
        apt-get install -y -qq docker-compose-v2 2>/dev/null || \
        dnf install -y -q docker-compose-plugin 2>/dev/null || \
        apk add --no-cache docker-compose 2>/dev/null || \
        echo "WARNING: Docker Compose not found. Please install it manually."
    fi
fi
REMOTE_SCRIPT
echo ""

# Sync code to server
echo "[3/6] Syncing code to server..."
rsync -avz --delete \
    --exclude='.git' \
    --exclude='node_modules' \
    --exclude='.env' \
    --exclude='.data' \
    --exclude='*.log' \
    -e "ssh $SSH_OPTS" \
    ./ "$REMOTE_USER@$SERVER_IP:$REMOTE_DIR/"
echo "✓ Code synced"
echo ""

# Generate .env file
echo "[4/6] Configuring environment..."
ssh $SSH_OPTS "$REMOTE_USER@$SERVER_IP" bash <<REMOTE_SCRIPT
cd $REMOTE_DIR

# Generate .env if not exists
if [ ! -f .env ]; then
    echo "Generating .env file..."
    
    # Generate random secrets
    ADMIN_PASSWORD=\$(openssl rand -hex 12)
    SESSION_SECRET=\$(openssl rand -hex 32)
    IMG_PROXY_SIGN_SECRET=\$(openssl rand -hex 32)
    POSTGRES_PASSWORD=\$(openssl rand -hex 32)
    
    cat > .env <<EOF
# AIHOT Environment Configuration
# Generated by deploy script on $(date -Iseconds)

# Site configuration
SITE_URL=http://$SERVER_IP:3000
SITE_NAME=车载行业动态
SITE_TAGLINE=法规·标准·技术·评测

# Admin access
ADMIN_PASSWORD=$ADMIN_PASSWORD

# Security secrets
SESSION_SECRET=$SESSION_SECRET
IMG_PROXY_SIGN_SECRET=$IMG_PROXY_SIGN_SECRET

# Database
POSTGRES_PASSWORD=$POSTGRES_PASSWORD

# Safety valves (enable for production)
COLLECT_ENABLED=true
MODEL_CALLS_ENABLED=true

# Optional: LLM API key (required for model calls)
# LLM_API_KEY=your-api-key-here

# Optional: Feishu integration
# FEISHU_APP_ID=
# FEISHU_APP_SECRET=
# FEISHU_TABLE_ENABLED=false

# Optional: IndexNow
# INDEXNOW_SUBMIT_ENABLED=false
EOF
    
    echo "✓ .env generated"
    echo ""
    echo "=== IMPORTANT: Save these credentials ==="
    echo "Admin password: $ADMIN_PASSWORD"
    echo "Postgres password: $POSTGRES_PASSWORD"
    echo "========================================="
    echo ""
else
    echo "✓ .env already exists"
fi
REMOTE_SCRIPT
echo ""

# Build and start services
echo "[5/6] Building and starting services..."
ssh $SSH_OPTS "$REMOTE_USER@$SERVER_IP" bash <<REMOTE_SCRIPT
cd $REMOTE_DIR

# Stop existing services if any
docker compose down 2>/dev/null || true

# Build images
echo "Building Docker images (this may take a few minutes)..."
docker compose build --pull

# Start services
echo "Starting services..."
docker compose up -d

# Wait for services to be healthy
echo "Waiting for services to start..."
sleep 10

# Check status
docker compose ps
REMOTE_SCRIPT
echo ""

# Final check
echo "[6/6] Verifying deployment..."
ssh $SSH_OPTS "$REMOTE_USER@$SERVER_IP" bash <<REMOTE_SCRIPT
cd $REMOTE_DIR

# Check if services are running
if docker compose ps | grep -q "api" && docker compose ps | grep -q "web"; then
    echo "✓ Services are running"
    echo ""
    echo "=== Deployment Complete ==="
    echo "Portal: http://$SERVER_IP:3000"
    echo "Admin: http://$SERVER_IP:3000/admin"
    echo ""
    echo "First-time setup:"
    echo "- Wait 1-2 minutes for initial data import"
    echo "- Check logs: docker compose logs -f"
    echo "- View status: docker compose ps"
else
    echo "ERROR: Services failed to start"
    echo "Check logs: docker compose logs"
    exit 1
fi
REMOTE_SCRIPT

echo ""
echo "=== Deployment finished successfully ==="
